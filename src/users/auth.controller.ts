import {
  Body,
  Controller,
  HttpCode,
  HttpStatus,
  Post,
  UnauthorizedException,
} from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiResponse } from '@nestjs/swagger';
import { CurrentUserId, Public } from './auth.guard';
import { AuthService } from './auth.service';
import { AuthenticateDto } from './dto/authenticate.dto';
import { RefreshTokenDto } from './dto/refreshToken.dto';
import { TokenResponseDto } from './dto/tokenResponse.dto';

@Controller('/auth')
export class AuthController {
  constructor(private readonly authService: AuthService) {}

  @Post('/exchange')
  @Public()
  @ApiOperation({
    summary: 'Create refresh and access tokens from an auth code',
  })
  @ApiResponse({ status: HttpStatus.CREATED, type: TokenResponseDto })
  async exchangeToken(
    @Body() body: AuthenticateDto,
  ): Promise<TokenResponseDto> {
    const user = await this.authService.getUserByAuthCode(body.code);
    if (!user) {
      throw new UnauthorizedException();
    }
    const { accessToken, expiresAt, refreshToken } =
      await this.authService.createRefreshToken(user);
    return {
      refreshToken: {
        expiresAt,
        token: refreshToken,
      },
      accessToken,
    };
  }

  @Post('/refresh')
  @Public()
  @ApiOperation({
    summary: 'Get a new access token',
    description:
      'This creates a new short-lived access token. The refresh token will be rotated and a new refresh token is returned, too.',
  })
  @ApiResponse({ status: HttpStatus.CREATED, type: TokenResponseDto })
  async refreshToken(@Body() body: RefreshTokenDto): Promise<TokenResponseDto> {
    const tokens = await this.authService.refreshToken(body.refreshToken);
    if (!tokens) {
      throw new UnauthorizedException();
    }
    return {
      refreshToken: {
        expiresAt: tokens.expiresAt,
        token: tokens.refreshToken,
      },
      accessToken: tokens.accessToken,
    };
  }

  @Post('/revoke')
  @Public()
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({
    summary: 'Revoke a refresh token',
    description:
      'This revokes the specified refresh token. Access tokens generated by this refresh token will continue to work until they expire.',
  })
  async revokeRefreshToken(@Body() body: RefreshTokenDto) {
    const revoked = await this.authService.revokeRefreshToken(
      body.refreshToken,
    );
    if (!revoked) {
      throw new UnauthorizedException();
    }
  }

  @ApiBearerAuth('access-token')
  @Post('/revoke-all')
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({
    summary: 'Revoke all refresh tokens',
    description:
      'This revokes all refresh token of the current user. All access tokens generated before will continue to work until they expire.',
  })
  async revokeAllRefreshTokens(@CurrentUserId() userId: number) {
    await this.authService.revokeAllRefreshTokensByUser(userId);
  }
}
